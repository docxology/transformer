def generate_comparison_report(
    runs: List[Any],
    metrics_to_compare: List[str],
    save_path: str = 'outputs/reports/comparison.html'
) -> Path:
    """
    Generate HTML comparison report for multiple runs.
    
    Args:
        runs: List of ReportMetrics objects or dictionaries
        metrics_to_compare: List of metric names to compare
        save_path: Path to save HTML report
        
    Returns:
        Path to saved report
    """
    save_path = Path(save_path)
    save_path.parent.mkdir(parents=True, exist_ok=True)
    
    html = _generate_comparison_html(runs, metrics_to_compare)
    
    with open(save_path, 'w', encoding='utf-8') as f:
        f.write(html)
    
    return save_path


