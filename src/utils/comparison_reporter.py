def _build_comparison_table(runs: List[Dict], metrics: List[str]) -> str:
    """Build comparison table HTML."""
    headers = ['Run', 'Timestamp'] + metrics
    
    rows_html = ""
    for idx, run in enumerate(runs):
        timestamp = run.get('timestamp', 'N/A')
        
        row_html = f"<tr><td>Run {idx+1}</td><td>{timestamp}</td>"
        
        for metric in metrics:
            value = _extract_nested_value(run, metric)
            row_html += f"<td>{value}</td>"
        
        row_html += "</tr>"
        rows_html += row_html
    
    return f"""
    <table>
        <thead>
            <tr>
                {''.join(f'<th>{h}</th>' for h in headers)}
            </tr>
        </thead>
        <tbody>
            {rows_html}
        </tbody>
    </table>
    """


def _build_metric_comparison(runs: List[Dict], metrics: List[str]) -> str:
    """Build metric comparison cards."""
    cards_html = ""
    
    for metric in metrics:
        values = []
        for run in runs:
            val = _extract_nested_value(run, metric)
            if val != 'N/A':
                try:
                    values.append(float(val))
                except:
                    values.append(None)
            else:
                values.append(None)
        
        # Find best and worst
        valid_values = [v for v in values if v is not None]
        if not valid_values:
            continue
        
        best_val = min(valid_values)
        worst_val = max(valid_values)
        
        rows_html = ""
        for idx, (run, val) in enumerate(zip(runs, values)):
            badge = ""
            if val == best_val:
                badge = '<span class="badge badge-best">BEST</span>'
            elif val == worst_val:
                badge = '<span class="badge badge-worst">WORST</span>'
            
            rows_html += f"""
            <div class="metric-row">
                <span class="metric-label">Run {idx+1}:</span>
                <span class="metric-value">{val if val is not None else 'N/A'} {badge}</span>
            </div>
            """
        
        cards_html += f"""
        <div class="metric-card">
            <h3>{metric.replace('_', ' ').title()}</h3>
            {rows_html}
        </div>
        """
    
    return cards_html


def _build_config_comparison(runs: List[Dict]) -> str:
    """Build configuration comparison section."""
    # Extract all unique config keys
    all_keys = set()
    for run in runs:
        config = run.get('model_config', {})
        all_keys.update(config.keys())
    
    if not all_keys:
        return "<p>No configuration data available.</p>"
    
    rows_html = ""
    for key in sorted(all_keys):
        row_html = f"<tr><td><code>{key}</code></td>"
        
        for run in runs:
            config = run.get('model_config', {})
            value = config.get(key, 'N/A')
            row_html += f"<td>{value}</td>"
        
        row_html += "</tr>"
        rows_html += row_html
    
    headers = ['Parameter'] + [f'Run {i+1}' for i in range(len(runs))]
    
    return f"""
    <table>
        <thead>
            <tr>
                {''.join(f'<th>{h}</th>' for h in headers)}
            </tr>
        </thead>
        <tbody>
            {rows_html}
        </tbody>
    </table>
    """


def _extract_nested_value(data: Dict, key: str) -> str:
    """Extract nested value from dictionary."""
    parts = key.split('.')
    current = data
    
    for part in parts:
        if isinstance(current, dict) and part in current:
            current = current[part]
        else:
            return 'N/A'
    
    if isinstance(current, (int, float)):
        return f'{current:.4f}' if isinstance(current, float) else str(current)
    
    return str(current)


def create_quick_comparison(
    run1: Any,
    run2: Any,
    label1: str = "Run 1",
    label2: str = "Run 2"
) -> Dict[str, Any]:
    """
    Quick comparison between two runs.
    
    Args:
        run1: First run data
        run2: Second run data
        label1: Label for first run
        label2: Label for second run
        
    Returns:
        Dictionary with comparison results
    """
    if hasattr(run1, 'to_dict'):
        data1 = run1.to_dict()
    else:
        data1 = run1
    
    if hasattr(run2, 'to_dict'):
        data2 = run2.to_dict()
    else:
        data2 = run2
    
    # Compare configurations
    config_diff = {}
    config1 = data1.get('model_config', {})
    config2 = data2.get('model_config', {})
    
    all_keys = set(config1.keys()) | set(config2.keys())
    for key in all_keys:
        val1 = config1.get(key)
        val2 = config2.get(key)
        if val1 != val2:
            config_diff[key] = {label1: val1, label2: val2}
    
    return {
        'label1': label1,
        'label2': label2,
        'config_differences': config_diff,
        'timestamp1': data1.get('timestamp'),
        'timestamp2': data2.get('timestamp')
    }



